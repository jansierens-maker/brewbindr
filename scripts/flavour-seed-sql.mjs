#!/usr/bin/env node
/**
 * Writes the SQL that loads the Flavour Lab knowledge base (data/flavour-lab.json) into Supabase.
 * Idempotent: rows are inserted or updated; links and ingredients that are no longer in the file
 * are removed. Paste the output into a new migration (and schema_update.sql) when the data change:
 *
 *   node scripts/flavour-seed-sql.mjs > /tmp/seed.sql
 */
import { readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const kb = JSON.parse(readFileSync(join(root, 'data/flavour-lab.json'), 'utf8'));

const q = v => (v === null || v === undefined ? 'NULL' : typeof v === 'number' ? String(v) : typeof v === 'boolean' ? String(v) : `'${String(v).replace(/'/g, "''")}'`);
const arr = a => (a?.length ? `ARRAY[${a.map(q).join(', ')}]::TEXT[]` : `'{}'::TEXT[]`);

const upsert = (table, cols, rows, key, values) => {
  if (!rows.length) return '';
  const update = cols.filter(c => !key.includes(c)).map(c => `${c} = EXCLUDED.${c}`).join(', ');
  return `INSERT INTO ${table} (${cols.join(', ')}) VALUES\n${rows.map(r => `  (${values(r).join(', ')})`).join(',\n')}\nON CONFLICT (${key.join(', ')}) DO ${update ? `UPDATE SET ${update}` : 'NOTHING'};\n`;
};

const out = [];
out.push(`-- Flavour Lab knowledge base, version ${kb.version} (generated by scripts/flavour-seed-sql.mjs)`);
out.push(upsert('flavour_families', ['id', 'name_nl', 'name_fr', 'name_en', 'color', 'sort'], kb.families, ['id'],
  f => [q(f.id), q(f.name_nl), q(f.name_fr), q(f.name_en), q(f.color), q(f.sort)]));
out.push(upsert('flavour_compounds', ['id', 'name', 'family_id', 'volatility', 'aroma_active', 'descriptor_nl', 'descriptor_fr', 'descriptor_en'], kb.compounds, ['id'],
  c => [q(c.id), q(c.name), q(c.family_id), q(c.volatility), q(c.aroma_active), q(c.descriptor_nl), q(c.descriptor_fr), q(c.descriptor_en)]));
out.push(upsert('flavour_sources', ['id', 'title', 'url', 'type', 'accessed_on', 'note'], kb.sources, ['id'],
  s => [q(s.id), q(s.title), q(s.url), q(s.type), `${q(s.accessed_on)}::DATE`, q(s.note)]));
out.push(upsert('flavour_ingredients',
  ['id', 'category', 'name_nl', 'name_fr', 'name_en', 'aliases', 'dose_min_g_per_l', 'dose_max_g_per_l', 'preferred_stage', 'form', 'yeast_pof', 'notes_nl', 'notes_fr', 'notes_en'],
  kb.ingredients, ['id'],
  i => [q(i.id), q(i.category), q(i.name_nl), q(i.name_fr), q(i.name_en), arr(i.aliases), q(i.dose_min_g_per_l), q(i.dose_max_g_per_l), q(i.preferred_stage), q(i.form), q(i.yeast_pof), q(i.notes_nl), q(i.notes_fr), q(i.notes_en)]));
out.push(`DELETE FROM flavour_ingredient_compounds l WHERE NOT EXISTS (SELECT 1 FROM (VALUES\n${kb.links.map(l => `  (${q(l.ingredient_id)}, ${q(l.compound_id)})`).join(',\n')}\n) AS k(ingredient_id, compound_id) WHERE k.ingredient_id = l.ingredient_id AND k.compound_id = l.compound_id);\n`);
out.push(`DELETE FROM flavour_ingredients WHERE id <> ALL (${arr(kb.ingredients.map(i => i.id))});\n`);
out.push(upsert('flavour_ingredient_compounds', ['ingredient_id', 'compound_id', 'intensity', 'source_id'], kb.links, ['ingredient_id', 'compound_id'],
  l => [q(l.ingredient_id), q(l.compound_id), q(l.intensity), q(l.source_id)]));
out.push(`INSERT INTO flavour_meta (key, value) VALUES ('version', ${q(kb.version)}) ON CONFLICT (key) DO UPDATE SET value = EXCLUDED.value;\n`);
process.stdout.write(out.join('\n'));
